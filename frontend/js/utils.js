/**
 * Format numeric value to Indonesian Rupiah (e.g. Rp2.500.000)
 */
export function formatIDR(amount) {
  const num = Number(amount) || 0;
  const isNegative = num < 0;
  const abs = Math.round(Math.abs(num));
  const formatted = abs.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return `${isNegative ? '-' : ''}Rp${formatted}`;
}

/**
 * Parse IDR input string to clean integer
 */
export function parseIDRInput(raw) {
  if (!raw && raw !== 0) return 0;
  const digits = raw.toString().replace(/\D/g, '');
  return digits ? parseInt(digits, 10) : 0;
}

/**
 * Format date to localized Indonesian format
 */
export function formatDateID(dateStr, options = {}) {
  if (!dateStr) return '—';
  const date = new Date(dateStr);
  if (isNaN(date.getTime())) return dateStr;

  const days = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
  const monthsFull = [
    'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
    'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'
  ];
  const monthsShort = [
    'Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun',
    'Jul', 'Agt', 'Sep', 'Okt', 'Nov', 'Des'
  ];

  const dayName = days[date.getDay()];
  const day = date.getDate();
  const month = options.shortMonth ? monthsShort[date.getMonth()] : monthsFull[date.getMonth()];
  const year = date.getFullYear();

  if (options.showDay) {
    return `${dayName}, ${day} ${month} ${year}`;
  }
  return `${day} ${month} ${year}`;
}

/**
 * Calculate days remaining in current month
 */
export function getDaysRemainingInMonth() {
  const now = new Date();
  const lastDay = new Date(now.getFullYear(), now.getMonth() + 1, 0).getDate();
  return Math.max(1, lastDay - now.getDate() + 1);
}

/**
 * Format relative due date (e.g. "5 hari lagi", "Besok", "Lewat 2 hari")
 */
export function formatRelativeDueDate(dueDateStr) {
  if (!dueDateStr) return { label: '—', isUrgent: false, isOverdue: false };

  const now = new Date();
  now.setHours(0, 0, 0, 0);
  const due = new Date(dueDateStr);
  due.setHours(0, 0, 0, 0);

  const diffTime = due.getTime() - now.getTime();
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  if (diffDays < 0) {
    return { label: `Lewat ${Math.abs(diffDays)} hari`, isUrgent: true, isOverdue: true };
  } else if (diffDays === 0) {
    return { label: 'Jatuh tempo hari ini', isUrgent: true, isOverdue: false };
  } else if (diffDays === 1) {
    return { label: 'Besok', isUrgent: true, isOverdue: false };
  } else if (diffDays <= 7) {
    return { label: `${diffDays} hari lagi`, isUrgent: true, isOverdue: false };
  } else {
    return { label: `Dalam ${diffDays} hari`, isUrgent: false, isOverdue: false };
  }
}

/**
 * Toast Notification Helper
 */
export function showToast(message, isSuccess = true) {
  let toastContainer = document.getElementById('toast-container');
  if (!toastContainer) {
    toastContainer = document.createElement('div');
    toastContainer.id = 'toast-container';
    toastContainer.className = 'toast-container';
    document.body.appendChild(toastContainer);
  }

  const toast = document.createElement('div');
  toast.className = `toast-item ${isSuccess ? 'success' : 'error'}`;
  toast.innerHTML = `
    <div class="toast-icon">
      ${isSuccess ? renderIcon('CheckCircle2', 18, 'var(--sage)') : renderIcon('AlertCircle', 18, 'var(--terracotta)')}
    </div>
    <div class="toast-text">${escapeHtml(message)}</div>
  `;

  toastContainer.appendChild(toast);

  // Trigger animation
  requestAnimationFrame(() => {
    toast.classList.add('visible');
  });

  setTimeout(() => {
    toast.classList.remove('visible');
    setTimeout(() => {
      toast.remove();
    }, 300);
  }, 3500);
}

/**
 * Debounce helper for inputs
 */
export function debounce(fn, delay = 250) {
  let timer;
  return function (...args) {
    clearTimeout(timer);
    timer = setTimeout(() => fn.apply(this, args), delay);
  };
}

/**
 * Escape HTML to prevent injection
 */
export function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

