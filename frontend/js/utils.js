/**
 * Format number to Indonesian Rupiah (e.g. Rp2.500.000)
 */
export function formatIDR(amount) {
  const isNegative = amount < 0;
  const abs = Math.round(Math.abs(amount || 0));
  const formatted = abs.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return `${isNegative ? '-' : ''}Rp${formatted}`;
}

/**
 * Parse IDR input string to numeric value
 */
export function parseIDRInput(raw) {
  if (!raw) return 0;
  const digits = raw.toString().replace(/\D/g, '');
  return digits ? parseInt(digits, 10) : 0;
}

/**
 * Format date to localized Indonesian format
 */
export function formatDateID(dateStr, options = {}) {
  if (!dateStr) return '';
  const date = new Date(dateStr);
  if (isNaN(date.getTime())) return dateStr;

  const days = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
  const monthsFull = [
    'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
    'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'
  ];
  const monthsShort = [
    'Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun',
    'Jul', 'Agt', 'Sep', 'Okt', 'Nov', 'Des'
  ];

  const dayName = days[date.getDay()];
  const day = date.getDate();
  const month = options.shortMonth ? monthsShort[date.getMonth()] : monthsFull[date.getMonth()];
  const year = date.getFullYear();

  if (options.showDay) {
    return `${dayName}, ${day} ${month} ${year}`;
  }
  return `${day} ${month} ${year}`;
}

/**
 * Format relative due date (e.g. "5 hari lagi", "Besok", "Jatuh tempo hari ini")
 */
export function formatRelativeDueDate(dueDateStr) {
  if (!dueDateStr) return { label: '-', isUrgent: false };

  const now = new Date();
  now.setHours(0, 0, 0, 0);
  const due = new Date(dueDateStr);
  due.setHours(0, 0, 0, 0);

  const diffTime = due.getTime() - now.getTime();
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  if (diffDays < 0) {
    return { label: `Lewat ${Math.abs(diffDays)} hari`, isUrgent: true };
  } else if (diffDays === 0) {
    return { label: 'Jatuh tempo hari ini', isUrgent: true };
  } else if (diffDays === 1) {
    return { label: 'Besok', isUrgent: true };
  } else if (diffDays <= 7) {
    return { label: `${diffDays} hari lagi`, isUrgent: true };
  } else {
    return { label: `Dalam ${diffDays} hari`, isUrgent: false };
  }
}

/**
 * Toast Notification Helper
 */
export function showToast(message, isSuccess = true) {
  let toastEl = document.getElementById('app-toast');
  if (!toastEl) {
    const container = document.createElement('div');
    container.className = 'toast-container';
    container.innerHTML = `
      <div id="app-toast" class="toast">
        <span id="toast-icon"></span>
        <span id="toast-message"></span>
      </div>
    `;
    document.body.appendChild(container);
    toastEl = document.getElementById('app-toast');
  }

  const iconEl = document.getElementById('toast-icon');
  const msgEl = document.getElementById('toast-message');

  iconEl.innerHTML = isSuccess
    ? renderIcon('CheckCircle2', 18, '#387C6D')
    : renderIcon('AlertCircle', 18, '#E9896A');
  msgEl.textContent = message;

  toastEl.classList.add('show');
  clearTimeout(window.__toastTimeout);
  window.__toastTimeout = setTimeout(() => {
    toastEl.classList.remove('show');
  }, 3500);
}

